#!/bin/bash
#
# BBSFirewall - certbot renewal hooks
# https://github.com/SysopNetwork/BBSFirewall
#
# Writes the certbot deploy hooks that copy a renewed certificate into
# BBSFirewall and restart it. Used by setup-certs.sh and setup-config-cert.sh;
# BBSFirewall also runs "refresh" when it starts, so hooks installed by an older
# version are brought up to date.
#
#   bash cert-hooks.sh install redirect|editor
#   bash cert-hooks.sh refresh      (only rewrites hooks that already exist)
#
set -euo pipefail

BBSFW_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LE_DIR="${BBSFW_LE_DIR:-/etc/letsencrypt}"
HOOK_DIR="$LE_DIR/renewal-hooks/deploy"
PM2_APP_NAME="bbsfirewall"
MARKER="# Auto-generated by BBSFirewall"

hook_file() {
  case "$1" in
    redirect) echo "$HOOK_DIR/bbsfirewall-reload.sh" ;;
    editor)   echo "$HOOK_DIR/bbsfirewall-config-editor-reload.sh" ;;
  esac
}

# write_hook <redirect|editor> <live certificate dir>
# certbot runs every deploy hook once per renewed certificate, so each hook
# ignores renewals of any other one. With RENEWED_LINEAGE unset (hook run by
# hand) it always acts. BBSFW_SKIP_RESTART is set by the Tools tab, which loads
# the certificate itself: a restart there would cut off its own cert run.
write_hook() {
  local dest="$BBSFW_DIR/certs" file tmp
  if [[ "$1" == "editor" ]]; then dest="$BBSFW_DIR/certs/config-editor"; fi
  file="$(hook_file "$1")"
  mkdir -p "$HOOK_DIR"
  tmp="$(mktemp "$LE_DIR/renewal-hooks/.bbsfw-hook.XXXXXX")"
  cat > "$tmp" << HOOKEOF
#!/bin/bash
$MARKER cert-hooks.sh
# Copies this renewed certificate into BBSFirewall and restarts it.
CERT_DIR="$2"
DEST="$dest"
if [ -n "\${RENEWED_LINEAGE:-}" ] && [ "\$(basename "\$RENEWED_LINEAGE")" != "\$(basename "\$CERT_DIR")" ]; then
  exit 0
fi
cp "\$CERT_DIR/fullchain.pem" "\$DEST/fullchain.pem" || exit 1
cp "\$CERT_DIR/privkey.pem"   "\$DEST/privkey.pem" || exit 1
chmod 640 "\$DEST/privkey.pem"
if [ -n "\${BBSFW_SKIP_RESTART:-}" ]; then exit 0; fi
if command -v pm2 >/dev/null 2>&1; then
  pm2 restart $PM2_APP_NAME --silent
fi
HOOKEOF
  if cmp -s "$tmp" "$file"; then rm -f "$tmp"; return 0; fi
  # Swap the file in whole: the old one may be running right now.
  chmod 755 "$tmp"
  mv "$tmp" "$file"
  echo "Renewal hook written: $file"
}

# Bring an existing hook up to date, keeping the certificate it was set up for.
# Hooks that BBSFirewall didn't write, or that belong to another install, are
# left alone.
refresh_hook() {
  local file cert
  file="$(hook_file "$1")"
  [[ -f "$file" ]] || return 0
  grep -qF "$MARKER" "$file" || return 0
  grep -qF -e "\"$BBSFW_DIR\"" -e "\"$BBSFW_DIR/" "$file" || return 0
  cert="$(sed -n 's/^CERT_DIR="\([^"$`\\]*\)"$/\1/p' "$file" | head -n 1)"
  [[ -n "$cert" ]] || return 0
  write_hook "$1" "$cert"
}

case "${1:-} ${2:-}" in
  "install redirect") refresh_hook editor;   write_hook redirect "$LE_DIR/live/bbsfirewall-web-redirect" ;;
  "install editor")   refresh_hook redirect; write_hook editor   "$LE_DIR/live/bbsfirewall-config-editor" ;;
  "refresh ")         refresh_hook redirect; refresh_hook editor ;;
  *) echo "Usage: bash cert-hooks.sh install redirect|editor, or: bash cert-hooks.sh refresh" >&2; exit 1 ;;
esac
